import os
import csv

# --- Global Variables --- #
# This list will store all expense dictionaries. Each dictionary represents a single expense.
expenses = []
# This variable will store the user's monthly budget, initialized to 0.0.
monthly_budget = 0.0

# --- Expense Management Functions --- #

# Function to add a new expense.
def add_expense():
  print('\n--- Add New Expense ---')
  # Get date, category, and description from the user.
  date = input('Enter date (YYYY-MM-DD): ')
  category = input('Enter category (e.g., Food, Travel, Utilities): ')

  # Loop to ensure the user enters a valid number for the amount.
  while True:
    try:
      amount = float(input('Enter amount spent: $'))
      # Ensure amount is not negative
      if amount < 0:
        print('Amount cannot be negative. Please enter a positive value.')
      else:
        break # Exit loop if a valid non-negative amount is entered
    except ValueError:
      print('Invalid amount. Please enter a numeric value (e.g., 25.50).')

  description = input('Enter a short description: ')

  # Create a dictionary to hold the details of the new expense.
  expense = {
      'date': date,
      'category': category,
      'amount': amount,
      'description': description,
  }

  # Add the newly created expense dictionary to the global 'expenses' list.
  expenses.append(expense)
  print('Expense added successfully!')

# Function to display all recorded expenses.
def view_expenses():
  print('\n--- Your Expenses ---')

  # Check if the 'expenses' list is empty. If so, inform the user.
  if not expenses:
    print('No expenses found yet. Add some expenses first!')
    return

  # Iterate through each expense dictionary in the 'expenses' list.
  for expense in expenses:
    # Extract details from the current expense dictionary.
    date = expense['date']
    category = expense['category']
    amount = expense['amount']
    description = expense['description']

    # Print the details of each expense in a formatted way.
    print(f'{date} | Category: {category} | Amount: ${amount:.2f} | Description: {description}')

# --- Budget Management Functions --- #

# Function to allow the user to set or update their monthly budget.
def set_monthly_budget():
  global monthly_budget # Declare 'monthly_budget' as global to modify the global variable.
  print('\n--- Set Monthly Budget ---')
  while True:
    try:
      new_budget = float(input('Enter your desired monthly budget: $'))
      # Ensure the budget is not negative.
      if new_budget >= 0:
        monthly_budget = new_budget
        print(f'Monthly budget successfully set to ${monthly_budget:.2f}.')
        break # Exit loop if a valid non-negative budget is entered.
      else:
        print('Budget cannot be negative. Please enter a positive value.')
    except ValueError:
      print('Invalid input. Please enter a numeric value for the budget (e.g., 1000.00).')

# Function to track expenses against the set budget.
def track_budget():
  print('\n--- Budget Tracker ---')

  # Check if a monthly budget has been set. If not, prompt the user.
  if monthly_budget <= 0:
    print('No monthly budget set. Please set a budget first using option 6.')
    return

  # Calculate the total amount spent from all recorded expenses.
  total_expenses = 0.0
  for expense in expenses:
    total_expenses += expense['amount'] # Add each expense amount to the total.

  print(f'Total Expenses Incurred: ${total_expenses:.2f}')
  print(f'Your Monthly Budget: ${monthly_budget:.2f}')

  # Compare total expenses with the monthly budget and provide feedback.
  if total_expenses > monthly_budget:
    print(f'Alert! You have exceeded your budget by ${total_expenses - monthly_budget:.2f}.')
  else:
    print(f'Remaining Budget: ${monthly_budget - total_expenses:.2f}.')

# --- File I/O Functions --- #

# Function to save all current expenses to a CSV file.
def save_expenses():
  # Only save if there are expenses to save.
  if not expenses:
    print('No expenses to save.')
    return

  print('\nSaving expenses to expenses.csv...')
  # Open 'expenses.csv' in write mode ('w'). 'newline=' prevents extra blank rows.
  # 'with open(...)' ensures the file is properly closed even if errors occur.
  with open('expenses.csv', 'w', newline='') as file:
    # Define the column headers for the CSV file.
    fieldnames = ['date', 'category', 'amount', 'description']
    # Create a DictWriter object to write dictionaries to the CSV file.
    writer = csv.DictWriter(file, fieldnames=fieldnames)

    writer.writeheader() # Write the header row to the CSV.
    writer.writerows(expenses) # Write all expense dictionaries as rows.
  print('Expenses saved successfully to expenses.csv!')

# Function to load expenses from a CSV file into the 'expenses' list.
def load_expenses():
  global expenses # Declare 'expenses' as global to modify the global list.
  print('\nLoading expenses from expenses.csv...')
  # Check if the 'expenses.csv' file exists before trying to open it.
  if os.path.exists('expenses.csv'):
    # Clear any existing expenses in the list before loading new ones.
    expenses.clear()
    with open('expenses.csv', 'r', newline='') as file:
      # Create a DictReader object to read rows as dictionaries from the CSV.
      reader = csv.DictReader(file)
      # Iterate over each row (which is a dictionary) in the CSV file.
      for row in reader:
        try:
          # Convert the 'amount' back to a float, as it's read as a string from CSV.
          row['amount'] = float(row['amount'])
          expenses.append(row) # Add the loaded expense to the global list.
        except ValueError:
          # Handle cases where 'amount' in the CSV might not be a valid number.
          print(f"Warning: Could not convert amount for row: {row}. Skipping this entry.")
    print(f'Successfully loaded {len(expenses)} expenses from expenses.csv.')
  else:
    print('No expenses file (expenses.csv) found. Starting with an empty expense list.')

# --- Main Program Flow --- #

# The main function that runs the expense tracker application.
def main_menu():
  # Automatically load expenses when the program starts to restore previous data.
  load_expenses()
  global monthly_budget # Ensure we can access/modify the global monthly_budget.

  # Main loop for the menu, runs until the user chooses to exit.
  while True:
    print('\n--- Personal Expense Tracker Menu ---')
    print('1. Add a New Expense')
    print('2. View All Expenses')
    print('3. Track Budget Progress')
    print('4. Save Expenses to File')
    print('5. Exit Program')

    choice = input('Enter your choice (1-5): ')

    # Use if/elif/else to perform actions based on user's choice.
    if choice == '1':
      add_expense()
    elif choice == '2':
      view_expenses()
    elif choice == '3':
      track_budget()
    elif choice == '4':
      save_expenses()
    elif choice == '5':
      # Before exiting, save the current expenses to prevent data loss.
      print('Exiting the program.')
      save_expenses()
      break # Exit the while loop, ending the program.
    else:
      print('Invalid choice. Please enter a number between 1 and 5.')

# Call the main menu function to start the application when the script is run.
main_menu()