import os
import csv

patient_vitals = []

def add_vitals():
  print('Add vitals')

  # Get patient name, temperature, heart rate, and age.
  pt_name = input('Patient name: ')

  # Loop to ensure that the user enters a valid number for temperature.
  while True:
      try:
          temp = float(input('Temperature: '))
          if temp < 0:
              print('Enter a valid number.')
          else:
              break
      except ValueError:
          print('Invalid input. Please enter a number.')

  # Loop to ensure that the user enters a valid heart rate
  while True:
      try:
          hrt_rte = float(input('Heart rate: '))
          if hrt_rte < 0:
              print('Enter a valid number.')
          else:
              break
      except ValueError:
          print('Invalid input. Please enter a number.')

  # Loop to ensure that the user enters a valid number for age
  while True:
      try:
          age = float(input('Age:'))
          if age < 0:
              print('Age must be a positive number.')
          else:
              break
      except ValueError:
          print('Invalid input. Please enter a number.')

  # Create a dictionary to hold the details of the new vital entry.
  vitals = {
     'Patient_Name': pt_name,
     'Heart_Rate': hrt_rte,
     'Temperature': temp,
     'Patient_Age': age,
  }

  # Add the newly created expense dictionary to the global patient vitals list.
  patient_vitals.append(vitals)
  print('Vitals added successfully.')

# Function to display patient vitals that were previously added
def view_vitals():
    print('View patient vital.')

    # Check to see if the patient vitals list is empty.
    if not patient_vitals:
        print('No vital signs found yet. Add some first!')
        return

    # Iterate through each vital dictionary in the patients list.
    for vitals in patient_vitals:
        # Extract details from the current vital dictionary.
        pt_name = vitals['Patient_Name']
        hrt_rte = vitals['Heart_Rate']
        temp = vitals['Temperature']
        age = vitals['Patient_Age']

        # Call track_hrt_rte to get the status
        status = track_hrt_rte(age, hrt_rte)

        # Print the details of the vitals in a formatted way.
        print(f'{pt_name} | Age: {age:.2f} |  Heart rate: {hrt_rte:.2f} | Temperature: {temp:.2f}')
        print(f'{pt_name} | Heart rate status: {status}')

# Function to track and categorize vitals
def track_hrt_rte(age, hrt_rte):
    print('\n---Heart Rate tracker---')

    # Classifies patient heart rate as below normal or above normal based on heart ranges by age.
    # Define ranges for heart rates by age.
    if age <= 1:
        min_hrt, max_hrt = 100, 190
    elif age <= 5:
        min_hrt, max_hrt = 90, 130
    elif age <= 12:
        min_hrt, max_hrt = 75, 115
    else:
        min_hrt, max_hrt = 60, 100

    # Heart rate evaluation
    if hrt_rte < min_hrt:
        status = 'Below average'
    elif hrt_rte > max_hrt:
        status = 'Above average'
    else:
        status = 'Average'

    return status

# Function to save all current patient vitals
def save_vitals():
    # Only save if vitals are there to save
    if not patient_vitals:
        print('No vitals to save.')
        return
    print('\nSaving patient vitals to patient_vitals.csv...')
    # Open vitals CSV in write mode.
    with open('patient_vitals.csv', 'w', newline='') as file:
        # Define the column headers
        fieldnames = ['Patient_Name', 'Heart_Rate', 'Temperature', 'Patient_Age']
        # Create a dictionary writer object to write dictionaries to the CSV file.
        writer = csv.DictWriter(file, fieldnames=fieldnames)

        writer.writeheader() # Write the header row to the CSV.
        writer.writerows(patient_vitals) # Write all vitals dictionaries as rows.
    print('Patient vitals saved successfully to patient_vitals.csv!')

# Function to load patient vitals from a CSV file into the vitals list
def load_vitals():
  global patient_vitals # Declare Patient vitals as global to modify the global list.
  print('\nLoading patient vitals from patient_vitals.csv...')
  # Check if the 'patient_vitals.csv' file exists before trying to open it.
  if os.path.exists('patient_vitals.csv'):
    # Clear any existing vitals in the list before loading new ones.
    patient_vitals.clear()
    with open('patient_vitals.csv', 'r', newline='') as file:
      # Create a DictReader object to read rows as dictionaries from the CSV.
      reader = csv.DictReader(file)
      # Iterate over each row (which is a dictionary) in the CSV file.
      for row in reader:
        try:
          # Convert the numeric columns back to float/numeric values from string.
          row['Heart_Rate'] = float(row['Heart_Rate'])
          row['Temperature'] = float(row['Temperature'])
          row['Patient_Age'] = float(row['Patient_Age'])
          patient_vitals.append(row) # Add the loaded vital dictionary to the global list.
        except ValueError:
          # Handle cases where numeric fields in the CSV might not be valid numbers.
          print(f"Warning: Could not convert data for row: {row}. Skipping this entry.")
    print(f'Successfully loaded {len(patient_vitals)} records from patient_vitals.csv.')
  else:
    print('No patient vitals file (patient_vitals.csv) found. Starting with an empty vitals list.')

# --- Main Program Flow --- #

# The main function that runs the patient vitals application.
def main_menu():
  # Automatically load vitals when the program starts to restore previous data.
  load_vitals()

  # Main loop for the menu, runs until the user chooses to exit.
  while True:
    print('\n--- Patient Vitals Tracker Menu ---')
    print('1. Add New Vitals')
    print('2. View Patient Vitals')
    print('3. Save Vitals to File')
    print('4. Exit Program')

    choice = input('Enter your choice (1-4): ')

    # Use if/elif/else to perform actions based on user's choice.
    if choice == '1':
      add_vitals()
    elif choice == '2':
      view_vitals()
    elif choice == '3':
      save_vitals()
    elif choice == '4':
      # Before exiting, save the current vitals to prevent data loss.
      print('Exiting the program.')
      save_vitals()
      break # Exit the while loop, ending the program.
    else:
      print('Invalid choice. Please enter a number between 1 and 4.')

# Call the main menu function to start the application when the script is run.
main_menu()